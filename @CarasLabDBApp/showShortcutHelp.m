function showShortcutHelp(fig, context)
%SHOWSHORTCUTHELP Show the keyboard shortcuts for one of the app's windows.
%
%   CarasLabDBApp.showShortcutHelp(fig, context) displays the shortcut list for
%   the window FIG, where CONTEXT is one of:
%       "main"      - the Explorer window
%       "form"      - the generic add/edit form (pFormDialog)
%       "login"     - the connection dialog
%       "export"    - the export-to-workspace prompt
%       "tags"      - the tag editor (showTagEditor)
%       "variables" - the variables editor (showVariableEditor)
%       "retract"   - the retraction dialog (showRetractDialog)
%       "husbandry" - the daily husbandry table (showHusbandryEntry)
%       "integrity" - the integrity report (showIntegrityReport)
%
%   Every window binds Ctrl+? to this method, so the lists have to live in one
%   place; kept apart they drift out of step with the callbacks they document.
%
%   See also CARASLABDBAPP, CARASLABDBAPP/BUILDUI, CARASLABDBAPP/PFORMDIALOG.

    arguments
        fig (1,1) matlab.ui.Figure
        context (1,1) string = "main"
    end

    switch context
        case "main"
            lines = [ ...
                "Ctrl+R           Refresh the current tab"; ...
                "Ctrl+E           Export the current table to the workspace"; ...
                "Ctrl+D           Edit / supersede the selected row"; ...
                "Ctrl+T           Tags of the selected row"; ...
                "Ctrl+L           Variables (named values) of the selected row"; ...
                "Ctrl+Delete      Retract the selected event or artifact"; ...
                "Ctrl+Shift+E     Add event"; ...
                "Ctrl+Shift+S     Add subject"; ...
                "Ctrl+Shift+N     Add session"; ...
                "Ctrl+H           Daily husbandry: weights and water for all animals"; ...
                "Ctrl+I           Integrity report"; ...
                "Enter            Apply filters (browse tabs)"; ...
                "Ctrl+Enter       Run the query (Custom SQL tab)"; ...
                "Esc              Clear all filters"; ...
                ""; ...
                "Tags filter:     stage:raw -qc:fail topic:*"; ...
                "                 all tokens must hold; -tok must not;"; ...
                "                 ns:* = any tag of ns; bare word = tag:word"; ...
                "Date filters:    a date written yyyy-MM-dd means that whole day"; ...
                "                 (Exact, and the upper end of a Range)"; ...
                "Active only:     untick to list every version; superseded and"; ...
                "                 retracted rows are then shown in grey"];
        case "form"
            lines = [ ...
                "Ctrl+S           Save (same as OK)"; ...
                "Enter            OK (unless the form has a multi-line field)"; ...
                "Esc              Cancel"; ...
                ""; ...
                "Shortcuts act while no text box has the focus:"; ...
                "                 click the form background or Tab to a button first."; ...
                "A field you empty is cleared; an untouched field is not rewritten."; ...
                "An edit or correction first lists what will change (old and new"; ...
                "                 value); nothing is written until you confirm."; ...
                "Numbers use a period as the decimal separator (71.9)."];
        case "login"
            lines = [ ...
                "Enter            Connect"; ...
                "Esc              Cancel"];
        case "export"
            lines = [ ...
                "Enter            Export"; ...
                "Esc              Cancel"];
        case "tags"
            lines = [ ...
                "Enter            Move to Add / Set for the typed value"; ...
                "Ctrl+Enter       Add the chosen tag"; ...
                "Ctrl+S           Set (replace) the chosen single-valued tag"; ...
                "Delete           Remove the tag selected in the list"; ...
                "Ctrl+R           Reload the tags from the database"; ...
                "Esc              Close"];
        case "variables"
            lines = [ ...
                "Ctrl+S           Save the typed value for the chosen variable"; ...
                "Ctrl+Enter       Save (same as Ctrl+S)"; ...
                "Delete           Unset the chosen variable on this row (asks first)"; ...
                "Ctrl+N           New variable: define it and set its first value"; ...
                "Ctrl+R           Reload the variables from the database"; ...
                "Esc              Close"; ...
                ""; ...
                "Selecting a row of the list chooses its variable."; ...
                "Typing a value never writes: only Save does."; ...
                "Shortcuts act while no text box has the focus:"; ...
                "                 Tab to a button or click the list first."; ...
                "Numbers use a period as the decimal separator (71.9)."];
        case "retract"
            lines = [ ...
                "Ctrl+S           Retract (a reason is required)"; ...
                "Esc              Cancel: nothing is written"; ...
                ""; ...
                "Shortcuts act while the reason box does not have the focus:"; ...
                "                 Tab to a button first."];
        case "husbandry"
            lines = [ ...
                "Ctrl+S           Check every cell, show the summary, then save"; ...
                "Esc              Cancel (asks before discarding entries)"; ...
                ""; ...
                "Enter / Tab      Finish editing a cell"; ...
                "Rows left blank are not written; all rows are saved together."; ...
                "Shortcuts act while no cell or text box is being edited."; ...
                "Numbers use a period as the decimal separator (71.9)."];
        case "integrity"
            lines = [ ...
                "Ctrl+R           Run the check again"; ...
                "Esc              Close"];
        otherwise
            lines = strings(0, 1);
    end

    lines = [lines; "Ctrl+?           Show this list"];
    uialert(fig, strjoin(lines, newline), "Keyboard shortcuts", "Icon", "info");
end
