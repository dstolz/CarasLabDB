%% CarasLabDB — usage walkthrough
% Demonstrates connecting to the lab metadata database and exercising the
% main insert / retrieve / supersede paths. This is a script for reading and
% adapting, not an automated test — it assumes a reachable database whose
% schema was created from design_docs/schema.sql.
%
% Put the parent of the @CarasLabDB folder on your path:
%     addpath("C:\src\CarasLabDB");

%% Connect (native postgresql interface; requires Database Toolbox)
% The current person is resolved by email and used for created_by /
% recorded_by on every insert below.
db = CarasLabDB( ...
    Username      = "lab_rw", ...
    Password      = "change-me", ...
    Server        = "nas-main.lab", ...
    Port          = 5432, ...
    DatabaseName  = "lab", ...
    PersonEmail   = "dstolz@umd.edu");

assert(db.isOpen())

%% Seed a person if needed, then point the object at them
% (Skip if the person already exists — email is UNIQUE.)
% pid = db.addPerson(FullName="Daniel Stolzberg", Email="dstolz@umd.edu", Role="PI");
% db.setPerson(PersonEmail="dstolz@umd.edu");

%% Reference / lookup rows
rootId = db.addStorageRoot(Name="nas-main", Description="primary NAS");
db.addProbe(Manufacturer="Cambridge NeuroTech", Model="H6", NChannels=64, ...
    Geometry=struct("layout", "linear", "pitch_um", 20));

%% A project (unique name), its members, and a project-level document
% Every subject must belong to a project, so create one first.
projId = db.addProject( ...
    Name        = "Gerbil AC plasticity", ...
    Description = "Auditory cortex plasticity in Mongolian gerbils", ...
    StartedOn   = datetime(2026, 1, 1));

% Associate one or more people with the project (many-to-many).
db.addProjectMember(ProjectId=projId, PersonId=db.CurrentPersonId, Role="PI");

% Attach project documents: NAS files and external links (Google Docs/Sheets).
db.addProjectArtifact(ProjectId=projId, Title="Grant aims", ...
    Kind="google_doc", Uri="https://docs.google.com/document/d/abc123/edit");
db.addProjectArtifact(ProjectId=projId, Title="Animal roster", ...
    Kind="google_sheet", Uri="https://docs.google.com/spreadsheets/d/def456/edit");
db.addProjectArtifact(ProjectId=projId, Title="Surgery protocol", ...
    Kind="file", ContentType="pdf", ...
    StorageRootId=rootId, RelativePath="projects/gerbil-ac/protocol.pdf");

%% A subject (associated with the project) and a session
db.addSubject( ...
    SubjectId    = "G-0421", ...
    ProjectId    = projId, ...
    SpeciesCode  = "meriones_unguiculatus", ...
    Sex          = "M", ...
    DateOfBirth  = datetime(2026, 1, 15));

sid = db.addSession( ...
    SubjectId     = "G-0421", ...
    Label         = "2026-07-02_pen1", ...
    StorageRootId = rootId, ...
    RelativePath  = "G-0421/2026-07-02_pen1", ...
    StartedAt     = datetime("now", "TimeZone", "local"), ...
    Rig           = "rig-A");

%% A recording event (must reference a session) + its raw artifact
eid = db.addRecordingEvent( ...
    SubjectId             = "G-0421", ...
    SessionId             = sid, ...
    OccurredAt            = datetime("now", "TimeZone", "local"), ...
    AcquisitionSystemCode = "intan_rhx", ...
    SampleRateHz          = 30000, ...
    NChannels             = 64, ...
    DurationS             = 1800, ...
    HardwareConfig        = struct("gain", 200, "reference", "common_median"));

rawId = db.addArtifact( ...
    ProducedByEventId = eid, ...
    StorageRootId     = rootId, ...
    SubjectId         = "G-0421", ...
    SessionId         = sid, ...
    RelativePath      = "G-0421/2026-07-02_pen1/raw.dat", ...
    Checksum          = "96856fa7376e06ee8614e194b4ca38a6372e1f7a32861a99b0ab10e680391bd7", ...
    ChecksumAlgo      = "sha256", ...
    SizeBytes         = 1.2e10, ...
    Role              = "raw", ...
    Format            = "dat");

%% Tags: label rows with namespace:value tags
% Every tag is namespace:value in lower case; a bare tag such as "pilot" is
% stored as tag:pilot. Each namespace carries a policy that the database
% enforces: stage is mutable and single-valued (one current stage per
% artifact, which moves on as the file is processed) with a closed
% vocabulary; cohort is immutable (set once, permanent); topic is
% multi-valued and open (new values are registered on first use).
nsArtifact = db.getTagNamespaces(AppliesTo="artifact");   % what can tag an artifact
stages     = db.getTags(Namespace="stage");               % raw, preprocessed, ...
disp(nsArtifact); disp(stages);

db.setTag("artifact", rawId, "stage:raw");
[~, changed] = db.setTag("artifact", rawId, "stage:raw");   % already set: nothing written
assert(~changed)
db.addTag("artifact", rawId, ["topic:tonotopy", "pilot"], Note="first penetration");
db.setTag("subject", "G-0421", "cohort:a");

% Preprocessing finished: move the file on. stage is single-valued, so
% setTag replaces stage:raw (the log keeps both the 'remove' and the 'add').
db.setTag("artifact", rawId, "stage:preprocessed");
disp(db.getEntityTags("artifact", rawId));                 % current tags
disp(db.getEntityTags("artifact", rawId, History=true));   % the full log

% Query by tag: the matching ids, or the rows through any get* method.
% Tags= must all be present, AnyTags= at least one, NotTags= none;
% "ns:*" means any tag of namespace ns.
preIds   = db.findByTags("artifact", Tags="stage:preprocessed", NotTags="qc:fail");
preRows  = db.getArtifacts(SessionId=sid, Tags="stage:preprocessed");
topical  = db.getArtifacts(Tags="topic:*");
cohortA  = db.getSubjects(Tags="cohort:a");
fprintf("preprocessed artifacts: %d (%d in this session); with a topic: %d\n", ...
    numel(preIds), height(preRows), height(topical));
disp(cohortA);

%% An analysis run that consumes the raw file and produces spikes
anId = db.addAnalysisEvent( ...
    SubjectId    = "G-0421", ...
    SessionId    = sid, ...
    OccurredAt   = datetime("now", "TimeZone", "local"), ...
    PipelineName = "kilosort4", ...
    CodeVersion  = "v4.0.1", ...
    Parameters   = struct("Th", [9 3], "nblocks", 5), ...
    Status       = "succeeded");

db.addEventInput(EventId=anId, ArtifactId=rawId, Role="raw");   % consumes

spikesId = db.addArtifact( ...
    ProducedByEventId = anId, ...
    StorageRootId     = rootId, ...
    SubjectId         = "G-0421", ...
    SessionId         = sid, ...
    RelativePath      = "G-0421/2026-07-02_pen1/spikes.npy", ...
    Checksum          = "89ea16571245ee09db9c76596ab6bdfb7b420545f038c0f16ca1bda7c9c7db13", ...
    Role              = "spikes", ...
    Format            = "npy");

%% Retrieval (defaults to the *_active views)
projects  = db.getProjects(Name="Gerbil AC plasticity");
members   = db.getProjectMembers(ProjectId=projId);
projDocs  = db.getProjectArtifacts(ProjectId=projId);
subjects  = db.getSubjects(ProjectId=projId);
events    = db.getEvents(SubjectId="G-0421");
artifacts = db.getArtifacts(SessionId=sid);
current   = db.getSubjectCurrent(SubjectId="G-0421");
disp(projects); disp(members); disp(projDocs);
disp(subjects); disp(events); disp(artifacts); disp(current);

% Full provenance ancestry of the spikes file.
lineage = db.artifactLineage(spikesId, Direction="up");
disp(lineage);

%% Correction via supersede (append-only: no UPDATE/DELETE)
% Log a weight, then correct it. The old husbandry row disappears from
% event_active; the new one carries supersedes -> old.
wEid = db.addHusbandryEvent( ...
    SubjectId  = "G-0421", ...
    OccurredAt = datetime("now", "TimeZone", "local"), ...
    Measure    = "weight", ...
    WeightG    = 72.4);

db.setTag("event", wEid, "qc:pass");

newWEid = db.supersedeEvent(wEid, ...
    DetailOverrides = struct("weight_g", 71.9), ...
    Notes           = "scale recalibrated");
fprintf("weight event %s superseded by %s\n", wEid, newWEid);
% The correction carries the event's current tags (qc:pass) forward in the
% same transaction, so it still matches every tag filter the original did.
disp(db.getEntityTags("event", newWEid));

%% Ad-hoc SQL escape hatch
n = db.runQuery("SELECT count(*) AS n FROM lab.event_active;");
fprintf("active events: %d\n", n.n(1));

%% Done
delete(db);   % closes the connection (since this object opened it)
